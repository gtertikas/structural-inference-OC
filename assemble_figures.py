"""
assemble_figures.py

Composites individual panel PNGs (generated by the MATLAB/R/Python pipeline)
into publication-ready compound figures following NHB layout standards:
  - double-column width: 180 mm
  - single-column width:  88 mm
  - min font size: 7 pt (inherited from source panels)
  - 300 DPI output, Arial bold panel labels (11 pt)

Figures produced
----------------
  Fig1_basic_behaviour.png/pdf   – panels a–e
  Fig2_factor_analysis.png/pdf   – panels a–c
  Fig3_OC_initial.png/pdf        – panels a–b
  Fig4_abPE.png/pdf              – panels a–d
  Fig5_sPE.png/pdf               – panels a–c, e–f
"""

