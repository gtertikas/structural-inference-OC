# ── helpers ──────────────────────────────────────────────────────────────────

def img(fname, crop_cols=None):
    """Load image; optionally crop to crop_cols=(start, end) column range."""
    data = mpimg.imread(os.path.join(FIG_DIR, fname))
    if crop_cols is not None:
        data = data[:, crop_cols[0]:crop_cols[1], :]
    return data

def show(ax, image):
    ax.imshow(image, interpolation='lanczos')
    ax.axis('off')

def plabel(ax, letter, x=-0.04, y=1.03):
    """NHB-style bold panel label, positioned just above top-left corner."""
    ax.text(x, y, letter,
            transform=ax.transAxes,
            fontsize=11, fontweight='bold',
            va='bottom', ha='right',
            fontfamily='Arial')

def save(name):
    for ext in ('png', 'pdf'):
        path = os.path.join(OUT_DIR, f'{name}.{ext}')
        plt.savefig(path, dpi=300, bbox_inches='tight', facecolor='white')
    plt.close()
    print(f'  saved: {name}.png / .pdf')


